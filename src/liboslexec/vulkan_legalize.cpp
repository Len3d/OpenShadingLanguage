// Data layout that clspv uses for spirv64 (taken from an LLVM module that
// clang produced for this target).  Modules coming from the CPU JIT carry no
// data layout at all, and clspv silently assumes one; being explicit keeps
// offsets and alignments predictable.
const char* kSpirv64DataLayout
    = "e-i64:64-v16:16-v24:32-v32:32-v48:64-v96:128-v192:256-v256:256-"
      "v512:512-v1024:1024-n8:16:32:64-G1";

class Retyper {
public:
    explicit Retyper(llvm::Module& mod) : M(mod), m_ctx(mod.getContext()) {}

    bool run(std::string& log);

private:
    // ---- type mapping ----
    llvm::Type* mapType(llvm::Type* T);

    // ---- constants / values ----
    llvm::Constant* mapConstant(llvm::Constant* C);
    llvm::Value* mapValue(llvm::Value* V);

    // ---- instruction rebuilding ----
    bool rebuildBody(llvm::Function* oldfn, llvm::Function* newfn, std::string& log);
    llvm::Value* recreate(llvm::Instruction& I, llvm::IRBuilder<>& B,
                          std::string& log);
    llvm::Function* intrinsicFor(llvm::IntrinsicInst* II,
                                 llvm::SmallVectorImpl<llvm::Value*>& args);

    // ---- per-invocation arena (replaces alloca) ----
    /// The shader-globals pointer of the function being rebuilt, or null when
    /// this function has no way to reach the arena (a helper that takes no
    /// sg argument).  Its first pointer argument is the ShaderGlobals by
    /// OSL's calling convention.
    llvm::Value* arenaBase();
    llvm::Function* arenaAllocFn();

    llvm::Module& M;
    llvm::LLVMContext& m_ctx;
    llvm::Function* m_new_fn = nullptr;

    llvm::DenseMap<llvm::Type*, llvm::Type*> m_types;
    std::map<llvm::Value*, llvm::Value*> m_values;  // old -> new
    std::map<llvm::Function*, llvm::Function*> m_functions;
    std::vector<std::pair<llvm::PHINode*, llvm::PHINode*>> m_phis;
};

/// The bump allocator that replaces `alloca` on the device.
///
/// Declared here so the rewriter can call it; the definition is in the
/// embedded device runtime (vulkan_shadeops.cpp).
static const char* kArenaAllocName = "osl_vk_arena_alloc";

llvm::Value* Retyper::arenaBase()
{
    if (!m_new_fn || m_new_fn->arg_empty())
        return nullptr;
    auto* PT = llvm::cast<llvm::PointerType>(m_new_fn->getArg(0)->getType());
    if (PT->getAddressSpace() != 1)
        return nullptr;
    return m_new_fn->getArg(0);
}

llvm::Function* Retyper::arenaAllocFn()
{
    // The definition arrives with the linked device runtime, so by the time a
    // body is rebuilt its *new* shell already exists (every function shell is
    // created before any body is).  Hand back that shell: calling the old
    // function object here would leave the rebuilt module pointing at a
    // function that the swap phase erases -- which prints as `call <badref>`.
    if (auto* F = M.getFunction(kArenaAllocName)) {
        auto it = m_functions.find(F);
        if (it != m_functions.end())
            return it->second;
        return F;
    }
    llvm::Type* ptr1 = llvm::PointerType::get(m_ctx, 1);
    llvm::Type* i64  = llvm::Type::getInt64Ty(m_ctx);
    llvm::Type* params[3] = { ptr1, i64, i64 };
    llvm::FunctionType* fty
        = llvm::FunctionType::get(ptr1, llvm::ArrayRef<llvm::Type*>(params, 3),
                                 false);
    return llvm::Function::Create(fty, llvm::Function::ExternalLinkage,
                                  kArenaAllocName, &M);
}

llvm::Type* Retyper::mapType(llvm::Type* T)
{
    if (!T)
        return nullptr;
    auto it = m_types.find(T);
    if (it != m_types.end())
        return it->second;

    llvm::Type* result = T;
    if (auto* PT = llvm::dyn_cast<llvm::PointerType>(T)) {
        // Everything OSL points at -- shader globals, the closure pool, the
        // constant tables its aggregates are copied out of -- lives in the one
        // storage buffer, so every pointer becomes address space 1.
        //
        // It used to become "generic" (address space 4) so that clspv's own
        // InferAddressSpaces could push it down to Private/Global.  That does
        // not survive contact with Vulkan: generic pointers only work in the
        // OpenCL memory model, and the lowering clspv performs for them goes
        // through integer arithmetic (`ptrtoint`/`inttoptr`), which SPIR-V
        // cannot express for a logical storage class -- it emits
        // `OpConvertUToPtr`, and that instruction requires
        // PhysicalStorageBufferAddresses.  Staying in address space 1 means
        // there is no address-space cast to lower in the first place; pointers
        // that are stored into the buffer (the closure pool cursor, sg.Ci) are
        // the one form Vulkan needs a capability for, and that capability is
        // SPV_KHR_variable_pointers.
        if (PT->getAddressSpace() == 0)
            result = llvm::PointerType::get(m_ctx, 1);
    } else if (auto* FT = llvm::dyn_cast<llvm::FunctionType>(T)) {
        llvm::SmallVector<llvm::Type*, 8> params;
        for (auto* P : FT->params())
            params.push_back(mapType(P));
        llvm::Type* ret = mapType(FT->getReturnType());
        result           = llvm::FunctionType::get(ret, params, FT->isVarArg());
    } else if (auto* AT = llvm::dyn_cast<llvm::ArrayType>(T)) {
        llvm::Type* el = mapType(AT->getElementType());
        if (el != AT->getElementType())
            result = llvm::ArrayType::get(el, AT->getNumElements());
    } else if (auto* VT = llvm::dyn_cast<llvm::FixedVectorType>(T)) {
        llvm::Type* el = mapType(VT->getElementType());
        if (el != VT->getElementType())
            result = llvm::FixedVectorType::get(el, VT->getNumElements());
    } else if (auto* ST = llvm::dyn_cast<llvm::StructType>(T)) {
        // Identified structs are owned by their name and cannot be recreated;
        // if any field would change we leave the struct alone (its fields are
        // then still reachable through the field access instructions, which
        // this pass rewrites individually).
        if (ST->isLiteral()) {
            llvm::SmallVector<llvm::Type*, 8> els;
            bool changed = false;
            for (auto* E : ST->elements()) {
                llvm::Type* NE = mapType(E);
                changed |= (NE != E);
                els.push_back(NE);
            }
            if (changed)
                result = llvm::StructType::get(m_ctx, els, ST->isPacked());
        }
    }

    m_types[T] = result;
    return result;
}

llvm::Constant* Retyper::mapConstant(llvm::Constant* C)
{
    if (!C)
        return nullptr;

    llvm::Type* NT = mapType(C->getType());
    if (NT == C->getType()) {
        // Type unchanged, but the constant may still hold values that need
        // remapping (aggregates holding globals, expressions, ...).
        if (auto* GV = llvm::dyn_cast<llvm::GlobalVariable>(C)) {
            auto it = m_values.find(GV);
            if (it != m_values.end() && it->second)
                return llvm::cast<llvm::Constant>(it->second);
            return C;
        }
        if (auto* F = llvm::dyn_cast<llvm::Function>(C)) {
            auto it = m_functions.find(F);
            if (it != m_functions.end())
                return it->second;
            return C;
        }
        if (auto* CS = llvm::dyn_cast<llvm::ConstantStruct>(C)) {
            llvm::SmallVector<llvm::Constant*, 8> ops;
            bool changed = false;
            for (auto& O : CS->operands()) {
                llvm::Constant* NO = mapConstant(llvm::cast<llvm::Constant>(O));
                changed |= (NO != O.get());
                ops.push_back(NO);
            }
            if (changed)
                return llvm::ConstantStruct::get(
                    llvm::cast<llvm::StructType>(NT), ops);
            return C;
        }
        if (auto* CA = llvm::dyn_cast<llvm::ConstantArray>(C)) {
            llvm::SmallVector<llvm::Constant*, 8> ops;
            bool changed = false;
            for (auto& O : CA->operands()) {
                llvm::Constant* NO = mapConstant(llvm::cast<llvm::Constant>(O));
                changed |= (NO != O.get());
                ops.push_back(NO);
            }
            if (changed)
                return llvm::ConstantArray::get(llvm::cast<llvm::ArrayType>(NT),
                                                ops);
            return C;
        }
        if (auto* CE = llvm::dyn_cast<llvm::ConstantExpr>(C)) {
            llvm::SmallVector<llvm::Constant*, 8> ops;
            bool changed = false;
            for (auto& O : CE->operands()) {
                llvm::Constant* NO = mapConstant(llvm::cast<llvm::Constant>(O));
                changed |= (NO != O.get());
                ops.push_back(NO);
            }
            if (changed)
                return llvm::ConstantExpr::get(
                    static_cast<llvm::Instruction::BinaryOps>(CE->getOpcode()),
                    ops[0], ops.size() > 1 ? ops[1] : nullptr);
            return C;
        }
        return C;
    }

    // The type changed: rebuild what we can, null out what a device can never
    // use (a baked host address).
    if (llvm::isa<llvm::ConstantPointerNull>(C))
        return llvm::ConstantPointerNull::get(
            llvm::cast<llvm::PointerType>(NT));
    if (llvm::isa<llvm::UndefValue>(C))
        return llvm::UndefValue::get(NT);
    if (auto* CE = llvm::dyn_cast<llvm::ConstantExpr>(C)) {
        if (CE->getOpcode() == llvm::Instruction::IntToPtr) {
            const std::string note = "inttoptr of a baked host address was "
                                     "replaced with null";
            if (g_dropped.insert(note).second)
                g_notes.push_back(note);
            return llvm::ConstantPointerNull::get(
                llvm::cast<llvm::PointerType>(NT));
        }
        if (CE->getOpcode() == llvm::Instruction::GetElementPtr) {
            llvm::SmallVector<llvm::Value*, 8> idx;
            for (unsigned i = 1; i < CE->getNumOperands(); ++i)
                idx.push_back(
                    mapConstant(llvm::cast<llvm::Constant>(CE->getOperand(i))));
            return llvm::cast<llvm::Constant>(llvm::ConstantExpr::getGetElementPtr(
                mapType(CE->getOperand(0)->getType()),
                mapConstant(llvm::cast<llvm::Constant>(CE->getOperand(0))), idx,
                llvm::cast<llvm::GEPOperator>(CE)->isInBounds()));
        }
        if (CE->getOpcode() == llvm::Instruction::BitCast)
            return llvm::ConstantExpr::getBitCast(
                mapConstant(llvm::cast<llvm::Constant>(CE->getOperand(0))), NT);
        if (CE->getOpcode() == llvm::Instruction::AddrSpaceCast)
            return llvm::ConstantExpr::getAddrSpaceCast(
                mapConstant(llvm::cast<llvm::Constant>(CE->getOperand(0))), NT);
    }
    if (llvm::isa<llvm::GlobalValue>(C)) {
        auto it = m_values.find(C);
        if (it != m_values.end() && it->second)
            return llvm::cast<llvm::Constant>(it->second);
        return C;
    }

    const std::string note = std::string("could not remap constant (opcode ")
                             + std::to_string(C->getValueID()) + ")";
    g_notes.push_back(note);
    return llvm::Constant::getNullValue(NT);
}

llvm::Value* Retyper::mapValue(llvm::Value* V)
{
    if (!V)
        return nullptr;
    auto it = m_values.find(V);
    if (it != m_values.end())
        return it->second;
    if (auto* C = llvm::dyn_cast<llvm::Constant>(V)) {
        llvm::Value* NC     = mapConstant(C);
        m_values[V]         = NC;
        return NC;
    }
    return V;  // an instruction is always rewritten in place before its users
}

llvm::Function* Retyper::intrinsicFor(llvm::IntrinsicInst* II,
                                      llvm::SmallVectorImpl<llvm::Value*>& args)
{
    // Intrinsic declarations are typed by their mangled name, so an overloaded
    // intrinsic whose pointer argument changed address space needs a fresh
    // declaration.  Build it from the overload list the intrinsic actually has.
    std::vector<llvm::Type*> overloads;
    switch (II->getIntrinsicID()) {
    case llvm::Intrinsic::memset:
    case llvm::Intrinsic::memcpy:
    case llvm::Intrinsic::memmove: {
        overloads.push_back(mapType(args[0]->getType()));
        if (II->getIntrinsicID() != llvm::Intrinsic::memset)
            overloads.push_back(mapType(args[1]->getType()));
        overloads.push_back(args[2]->getType());  // length
        break;
    }
    case llvm::Intrinsic::lifetime_start:
    case llvm::Intrinsic::lifetime_end:
#if OSL_LLVM_VERSION >= 240
        // LLVM 24 removed the size argument: llvm.lifetime.start/end take the
        // pointer alone and are overloaded on the pointer type.
        overloads.push_back(mapType(args[0]->getType()));
#else
        overloads.push_back(mapType(args[1]->getType()));
#endif
        break;
    default:
        // Any other intrinsic is left alone.  Two reasons:
        //  - most of them (llvm.smax.i32, llvm.fabs.f32, ...) have no pointer
        //    parameter, so their declaration does not need changing at all;
        //  - `Intrinsic::getDeclaration()` *requires* exactly the right
        //    overload list for an overloaded intrinsic, and passing an empty
        //    list where one is expected is an immediate crash in a release
        //    build.  Touching only the intrinsics we actually know about keeps
        //    that from happening (the first symptom was a hard crash on
        //    llvm.smax.i32 inside the closure allocator).
        return II->getCalledFunction();
    }
#if OSL_LLVM_VERSION >= 240
    // LLVM 24 dropped getDeclaration(); getOrInsertDeclaration() behaves the
    // same for an already-declared intrinsic.
    return llvm::Intrinsic::getOrInsertDeclaration(&M, II->getIntrinsicID(),
                                                   overloads);
#else
    return llvm::Intrinsic::getDeclaration(&M, II->getIntrinsicID(), overloads);
#endif
}

// Byte offsets into ShadeBlock that the Vulkan runtime addresses by *offset*
// rather than by pointer; must agree with vulkan_abi_check.cpp.
static const long long kShadeBlockRenderstateOffset = 216;
static const long long kShadeBlockCiOffset          = 288;
static const long long kShadeBlockPoolOffset        = 320;

/// True when `p` is a byte-field access `getelementptr i8, ptr <shaderglobals>,
/// i64 <off>` -- i.e. a constant-offset field of the ShadeBlock.
static bool isShadeBlockByteField(llvm::Value* p, long long off)
{
    auto* G = llvm::dyn_cast<llvm::GetElementPtrInst>(p);
    if (!G || !G->getSourceElementType()->isIntegerTy(8) || G->getNumOperands() != 2)
        return false;
    auto* C = llvm::dyn_cast<llvm::ConstantInt>(G->getOperand(1));
    return C && (long long)C->getSExtValue() == off;
}


/// The value an address chain starts from, however many links it has: the
/// front end writes the second slot of a two-pointer parameter block as
/// `inttoptr(add(ptrtoint(gep), 8))`, the latter half of which is the
/// `inttoptr` round trip this pass otherwise only folds away.
static llvm::Value* address_base(llvm::Value* p)
{
    using namespace llvm;
    for (int guard = 0; guard < 16; ++guard) {
        if (auto* G = dyn_cast<GetElementPtrInst>(p)) {
            p = G->getPointerOperand();
        } else if (auto* I = dyn_cast<IntToPtrInst>(p)) {
            auto* A = dyn_cast<BinaryOperator>(I->getOperand(0));
            if (!A || A->getOpcode() != Instruction::Add)
                return nullptr;
            Value* base = nullptr;
            for (unsigned k = 0; k < 2; ++k) {
                if (auto* P = dyn_cast<PtrToIntInst>(A->getOperand(k))) {
                    base = P->getPointerOperand();
                    break;
                }
            }
            if (!base)
                return nullptr;
            p = base;
        } else {
            return p;
        }
    }
    return p;
}


/// True when `p` addresses a closure component's parameter block: that memory
/// comes from the arena allocator reached through
/// `osl_allocate[_weighted]_closure_component`.
static bool is_closure_component_param(llvm::Value* p)
{
    auto* C = llvm::dyn_cast<llvm::CallBase>(address_base(p));
    if (!C)
        return false;
    llvm::Value* co = C->getCalledOperand()->stripPointerCasts();
    llvm::StringRef name;
    if (auto* F = llvm::dyn_cast<llvm::Function>(co))
        name = F->getName();
    else if (auto* GV = llvm::dyn_cast<llvm::GlobalValue>(co))
        name = GV->getName();
    return name.contains("closure_component");
}


llvm::Value* Retyper::recreate(llvm::Instruction& I, llvm::IRBuilder<>& B,
                               std::string& log)
{
    using namespace llvm;
    g_rewritten_opcodes.insert(I.getOpcodeName());

    auto arg = [&](unsigned i) { return mapValue(I.getOperand(i)); };

    switch (I.getOpcode()) {
    case Instruction::Alloca: {
        auto& AI = cast<AllocaInst>(I);
        Type* ET = mapType(AI.getAllocatedType());
        // `alloca` cannot produce a pointer in address space 1: an alloca is
        // Private storage by definition, and a pointer to it could then never
        // reach the shader globals or the closure pool without an
        // address-space cast (which is exactly what Vulkan cannot do).
        //
        // Hand the storage out of the per-invocation arena instead, which lives
        // at the far end of the same storage buffer as everything else, so the
        // pointer it hands back has the address space every consumer expects.
        Value* sg = arenaBase();
        if (sg) {
            const llvm::DataLayout& DL = M.getDataLayout();
            uint64_t size = DL.getTypeAllocSize(ET);
            Function* alloc = arenaAllocFn();
            llvm::Value* args[3]
                = { sg, B.getInt64(size), B.getInt64(16) };
            return B.CreateCall(
                alloc->getFunctionType(), alloc, llvm::ArrayRef<llvm::Value*>(args, 3),
                AI.getName());
        }
        unsigned AS = cast<PointerType>(mapType(AI.getType()))->getAddressSpace();
        AllocaInst* NA = B.CreateAlloca(ET, AS,
                                        AI.isArrayAllocation() ? arg(0) : nullptr,
                                        AI.getName());
        NA->setAlignment(AI.getAlign());
        return NA;
    }
    case Instruction::Load: {
        auto& LI = cast<LoadInst>(I);
        LoadInst* NL = B.CreateLoad(mapType(LI.getType()), arg(0), LI.getName());
        NL->setAlignment(LI.getAlign());
        NL->setVolatile(LI.isVolatile());
        return NL;
    }
    case Instruction::Store: {
        auto& SI = cast<StoreInst>(I);

        // A pointer value stored into the ShadeBlock's closure-root field is
        // the one shape this backend cannot express: SPIR-V has no variable
        // pointers, so clspv treats pointer-in-memory as UB (it emits
        // `store i1 true, ptr poison` for a whole module that does it) and
        // aborts with llvm_unreachable in GetArgKindForType() for the small
        // case.  The device runtime publishes exactly the same fact as a
        // 32-bit arena offset (arena_set_root() in vulkan_shadeops.cpp), so
        // this store carries no information the host cannot already get;
        // dropping it is what makes the module compilable.
        if (SI.getValueOperand()->getType()->isPointerTy()
            && isShadeBlockByteField(SI.getPointerOperand(), kShadeBlockCiOffset)) {
            if (getenv("OSL_VULKAN_LEGALIZE_TRACE"))
                fprintf(stderr,
                        "[legalize] dropped pointer store to sg+%lld (Ci)\n",
                        kShadeBlockCiOffset);
            return B.getInt32(0);  // no value is consumed from a store
        }

        // A closure pointer stored into a component's parameter block is the
        // same shape again, and `layer(top, base)` is the only closure that
        // writes one.  The device runtime walks each tree by arena offset --
        // osl_add_closure_closure (vulkan_shadeops.cpp) already publishes its
        // two children that way -- so publish the layer's the same way rather
        // than leave a pointer value in the buffer for later to trip over.
        if (SI.getValueOperand()->getType()->isPointerTy()
            && is_closure_component_param(SI.getPointerOperand())) {
            llvm::Value* sg = arenaBase();
            if (sg) {
                llvm::Type* i8  = llvm::Type::getInt8Ty(m_ctx);
                llvm::Type* i64 = llvm::Type::getInt64Ty(m_ctx);
                llvm::Value* pool
                    = B.CreateGEP(i8, sg, B.getInt64(kShadeBlockPoolOffset));
#if OSL_LLVM_VERSION >= 240
                llvm::Value* from = B.CreatePtrToAddr(arg(0));
                llvm::Value* base = B.CreatePtrToAddr(pool);
                if (from->getType() != i64)
                    from = B.CreateZExt(from, i64);
                if (base->getType() != i64)
                    base = B.CreateZExt(base, i64);
#else
                llvm::Value* from = B.CreatePtrToInt(arg(0), i64);
                llvm::Value* base = B.CreatePtrToInt(pool, i64);
#endif
                StoreInst* NS = B.CreateStore(B.CreateSub(from, base), arg(1));
                NS->setAlignment(SI.getAlign());
                NS->setVolatile(SI.isVolatile());
                return NS;
            }
        }

        StoreInst* NS = B.CreateStore(arg(0), arg(1));
        NS->setAlignment(SI.getAlign());
        NS->setVolatile(SI.isVolatile());
        return NS;
    }
    case Instruction::GetElementPtr: {
        auto& GI = cast<GetElementPtrInst>(I);
        SmallVector<Value*, 8> idx;
        for (unsigned i = 1; i < GI.getNumOperands(); ++i)
            idx.push_back(arg(i));
        GetElementPtrInst* NG
            = dyn_cast<GetElementPtrInst>(B.CreateGEP(mapType(GI.getSourceElementType()),
                                                      arg(0), idx, GI.getName()));
        if (NG)
            NG->setIsInBounds(GI.isInBounds());
        return NG;
    }
    case Instruction::BitCast: {
        // Pointer <-> vector bitcasts are legal only for integral address
        // spaces; once the pointers live in address space 4 the verifier
        // rejects `bitcast <2 x float> to ptr addrspace(4)` outright.  OSL does
        // pun Vec2 through pointers, so route those through the integer of the
        // same width instead.
        Value* Src        = arg(0);
        Type* SrcTy       = Src->getType();
        Type* DstTy       = mapType(I.getType());
        bool src_is_ptr   = SrcTy->isPointerTy();
        bool dst_is_ptr   = DstTy->isPointerTy();
        if (src_is_ptr != dst_is_ptr) {
            const llvm::DataLayout& DL = M.getDataLayout();
            llvm::Type* int_ty = IntegerType::get(
                m_ctx, DL.getTypeSizeInBits(src_is_ptr ? DstTy : SrcTy));
            if (src_is_ptr) {
                Value* iv = B.CreatePtrToInt(Src, int_ty);
                return B.CreateBitCast(iv, DstTy);
            } else {
                Value* iv = B.CreateBitCast(Src, int_ty);
                return B.CreateIntToPtr(iv, DstTy);
            }
        }
        return B.CreateBitCast(Src, DstTy, I.getName());
    }
    case Instruction::AddrSpaceCast:
    case Instruction::PtrToInt:
#if OSL_LLVM_VERSION >= 240
    // LLVM 24 added `ptrtoaddr`: the address of a pointer as an integer, with
    // provenance preserved.  Device pointers are plain offsets in the Vulkan
    // model, so a ptrtoint is the correct lowering here.
    case Instruction::PtrToAddr:
#endif
    case Instruction::IntToPtr:
    case Instruction::Trunc:
    case Instruction::ZExt:
    case Instruction::SExt:
    case Instruction::FPTrunc:
    case Instruction::FPExt:
    case Instruction::FPToUI:
    case Instruction::FPToSI:
    case Instruction::UIToFP:
    case Instruction::SIToFP: {
        auto op = static_cast<Instruction::CastOps>(I.getOpcode());
        return B.CreateCast(op, arg(0), mapType(I.getType()), I.getName());
    }
    case Instruction::Add:
    case Instruction::FAdd:
    case Instruction::Sub:
    case Instruction::FSub:
    case Instruction::Mul:
    case Instruction::FMul:
    case Instruction::UDiv:
    case Instruction::SDiv:
    case Instruction::FDiv:
    case Instruction::URem:
    case Instruction::SRem:
    case Instruction::FRem:
    case Instruction::Shl:
    case Instruction::LShr:
    case Instruction::AShr:
    case Instruction::And:
    case Instruction::Or:
    case Instruction::Xor: {
        auto op = static_cast<Instruction::BinaryOps>(I.getOpcode());
        return B.CreateBinOp(op, arg(0), arg(1), I.getName());
    }
    case Instruction::ICmp: {
        auto& CI = cast<ICmpInst>(I);
        return B.CreateICmp(CI.getPredicate(), arg(0), arg(1), I.getName());
    }
    case Instruction::FCmp: {
        auto& CI = cast<FCmpInst>(I);
        return B.CreateFCmp(CI.getPredicate(), arg(0), arg(1), I.getName());
    }
    case Instruction::Select:
        return B.CreateSelect(arg(0), arg(1), arg(2), I.getName());
    case Instruction::PHI: {
        PHINode* NP = B.CreatePHI(mapType(I.getType()),
                                  cast<PHINode>(I).getNumIncomingValues(),
                                  I.getName());
        m_phis.emplace_back(&cast<PHINode>(I), NP);
        return NP;
    }
#if OSL_LLVM_VERSION >= 240
    // LLVM 24 split BranchInst into UncondBrInst / CondBrInst.
    case Instruction::UncondBr: {
        auto& BR = cast<UncondBrInst>(I);
        return B.CreateBr(cast<BasicBlock>(mapValue(BR.getSuccessor(0))));
    }
    case Instruction::CondBr: {
        auto& BR = cast<CondBrInst>(I);
        BasicBlock* T = cast<BasicBlock>(mapValue(BR.getSuccessor(0)));
        BasicBlock* F = cast<BasicBlock>(mapValue(BR.getSuccessor(1)));
        return B.CreateCondBr(arg(0), T, F);
    }
#else
    case Instruction::Br: {
        auto& BR = cast<BranchInst>(I);
        BasicBlock* T = cast<BasicBlock>(mapValue(BR.getSuccessor(0)));
        if (BR.isUnconditional())
            return B.CreateBr(T);
        BasicBlock* F = cast<BasicBlock>(mapValue(BR.getSuccessor(1)));
        return B.CreateCondBr(arg(0), T, F);
    }
#endif
    case Instruction::Switch: {
        auto& SW = cast<SwitchInst>(I);
        BasicBlock* Def = cast<BasicBlock>(mapValue(SW.getDefaultDest()));
        SwitchInst* NS  = B.CreateSwitch(arg(0), Def, SW.getNumCases());
        for (auto& C : SW.cases())
            NS->addCase(cast<ConstantInt>(mapConstant(C.getCaseValue())),
                        cast<BasicBlock>(mapValue(C.getCaseSuccessor())));
        return NS;
    }
    case Instruction::Ret: {
        auto& RI = cast<ReturnInst>(I);
        if (RI.getReturnValue())
            return B.CreateRet(arg(0));
        return B.CreateRetVoid();
    }
    case Instruction::Unreachable:
        return B.CreateUnreachable();
    case Instruction::ExtractValue: {
        auto& EI = cast<ExtractValueInst>(I);
        return B.CreateExtractValue(arg(0), EI.getIndices(), EI.getName());
    }
    case Instruction::ExtractElement: {
        // Vectors indexed at a constant (a `<3 x float>` swizzle such as the
        // color components ward.osl pulls out) arrive as extractelement, which
        // clspv accepts as long as the index is an i32.  Keep the index operand
        // mapped like every other argument.
        auto& EE = cast<ExtractElementInst>(I);
        return B.CreateExtractElement(arg(0), arg(1), EE.getName());
    }
    case Instruction::InsertElement: {
        auto& IE = cast<InsertElementInst>(I);
        return B.CreateInsertElement(arg(0), arg(1), arg(2), IE.getName());
    }
    case Instruction::ShuffleVector: {
        auto& SV = cast<ShuffleVectorInst>(I);
        return B.CreateShuffleVector(arg(0), arg(1), SV.getShuffleMask(),
                                     SV.getName());
    }
    case Instruction::InsertValue: {
        auto& II = cast<InsertValueInst>(I);
        return B.CreateInsertValue(arg(0), arg(1), II.getIndices(),
                                   II.getName());
    }
    case Instruction::Call: {
        auto& CI = cast<CallInst>(I);
        SmallVector<Value*, 16> args;
        for (unsigned i = 0; i < CI.arg_size(); ++i)
            args.push_back(arg(i));

        Value* callee   = CI.getCalledOperand();
        FunctionType* FT = nullptr;
        if (auto* II2 = dyn_cast<IntrinsicInst>(&I)) {
            Function* IF = intrinsicFor(II2, args);
            callee       = IF;
            FT           = IF->getFunctionType();
        } else if (auto* F = dyn_cast<Function>(callee)) {
            auto it = m_functions.find(F);
            if (it != m_functions.end())
                callee = it->second;
            FT = cast<FunctionType>(
                mapType(cast<Function>(callee)->getFunctionType()));
        } else {
            // Indirect call: the signature travels with the call itself.
            callee = mapValue(callee);
            FT     = cast<FunctionType>(mapType(CI.getFunctionType()));
        }

        CallInst* NC = B.CreateCall(FT, callee, args, CI.getName());
        NC->setCallingConv(CI.getCallingConv());
        NC->setTailCallKind(CI.getTailCallKind());
        return NC;
    }
    case Instruction::FNeg:
        // Plain, legal in SPIR-V; it shows up now that the device runtime has
        // code like `-dsdx` in it (the texture mip selection).
        return B.CreateFNeg(arg(0), I.getName());
    default:
        log += std::string("unsupported instruction: ") + I.getOpcodeName()
               + "\n";
        return nullptr;
    }
}

bool Retyper::rebuildBody(llvm::Function* oldfn, llvm::Function* newfn,
                          std::string& log)
{
    using namespace llvm;

    m_new_fn = newfn;

    // Blocks first, so branch targets resolve.
    std::vector<BasicBlock*> newblocks;
    for (auto& BB : *oldfn) {
        BasicBlock* NB = BasicBlock::Create(m_ctx, BB.getName(), newfn);
        m_values[&BB]      = NB;
        newblocks.push_back(NB);
    }

    std::vector<Instruction*> order;
    // Blocks must be walked in reverse post-order, not in the order they happen
    // to be printed: a value defined in a predecessor block is legal to use in
    // a later block even when the printer numbers it higher, and mapValue()
    // would then hand the rebuild a value from the *old* body.
    for (auto* BB : llvm::ReversePostOrderTraversal<Function*>(oldfn))
        for (auto& I : *BB)
            order.push_back(&I);

    for (auto* I : order) {
        // Per-instruction trace, off by default: when the rewriter dies inside
        // rebuildBody the last line printed names the instruction responsible.
        if (getenv("OSL_VULKAN_LEGALIZE_TRACE_IR")) {
            fprintf(stderr, "[legalize]     ");
            I->print(llvm::errs());
            fprintf(stderr, "\n");
        }
        BasicBlock* NB = cast<BasicBlock>(mapValue(I->getParent()));
#if OSL_LLVM_VERSION >= 240
        // LLVM 24 verifies llvm.lifetime.start/end against the argument being
        // an alloca, and every alloca has become an arena_alloc() call by now,
        // so these calls are unconditionally invalid.  They say nothing about
        // the arena storage anyway -- drop them.
        if (auto* II = dyn_cast<IntrinsicInst>(I)) {
            auto id = II->getIntrinsicID();
            if (id == llvm::Intrinsic::lifetime_start
                || id == llvm::Intrinsic::lifetime_end) {
                g_dropped.insert("lifetime intrinsic");
                continue;
            }
        }
#endif
        IRBuilder<> B(NB);
        Value* NV = recreate(*I, B, log);
        if (!NV)
            return false;
        if (NV->getName().empty() && I->hasName())
            NV->setName(I->getName());
        if (llvm::isa<Instruction>(NV))
            cast<Instruction>(NV)->setDebugLoc(I->getDebugLoc());
        m_values[I] = NV;

        // Successors of terminator instructions are blocks, already mapped.
    }

    // PHI operands can only be filled once every block exists.
    for (auto& P : m_phis) {
        PHINode* OP = P.first;
        PHINode* NP = P.second;
        if (OP->getParent()->getParent() != oldfn)
            continue;
        for (unsigned i = 0; i < OP->getNumIncomingValues(); ++i) {
            Value* NV = mapValue(OP->getIncomingValue(i));
            BasicBlock* NB = cast<BasicBlock>(mapValue(OP->getIncomingBlock(i)));
            NP->addIncoming(NV, NB);
        }
    }
    m_phis.clear();

    // Sanity check: no rebuilt instruction may still refer to an instruction of
    // the old function.  A dangling operand would be a use-after-free the
    // moment the old body is dropped.
    for (auto& BB : *newfn) {
        for (auto& I : BB) {
            for (auto& Op : I.operands()) {
                if (auto* OI = llvm::dyn_cast<llvm::Instruction>(Op.get())) {
                    if (OI->getFunction() == oldfn) {
                        log += "dangling operand from the old body in ";
                        log += I.getOpcodeName();
                        log += ": ";
                        log += OI->getOpcodeName();
                        log += "\n";
                        return false;
                    }
                }
            }
        }
    }
    return true;
}

bool Retyper::run(std::string& log)
{
    using namespace llvm;

    vulkan_set_module_target(M);

    // 1. Retype globals (external ones can be mutated in place).
    std::vector<GlobalVariable*> gvs;
    for (auto& G : M.globals())
        gvs.push_back(&G);
    for (auto* G : gvs) {
        Type* NT = mapType(G->getValueType());
        // A global's *address space* matters as much as its value type: a
        // constant living in address space 0 cannot be handed to a routine that
        // now takes a storage-buffer pointer.  (This is how the device runtime's
        // constant Vec3 tables broke llvm.memcpy: the declaration was rebuilt
        // as .p1.p1 while the global it points at was still .p0.)
        unsigned NASA = (G->getAddressSpace() == 0) ? 1u : G->getAddressSpace();
        if (NT == G->getValueType() && NASA == G->getAddressSpace())
            continue;
        if (G->isDeclaration()) {
            G->mutateType(NT);
        } else {
            GlobalVariable* NG = new GlobalVariable(
                M, NT, G->isConstant(), G->getLinkage(),
                mapConstant(G->getInitializer()), G->getName(), G,
                G->getThreadLocalMode(), NASA);
            NG->copyAttributesFrom(G);
            m_values[G] = NG;
        }
    }

    // 2. Create shells for every function that needs a new signature.
    //    Declarations are re-created as well (Function has no API to change its
    //    type in place), so call sites always see one consistent object.
    std::vector<Function*> defs;
    std::vector<Function*> decls;
    for (auto& F : M) {
        FunctionType* NFT = cast<FunctionType>(mapType(F.getFunctionType()));
        if (F.isDeclaration()) {
            // Intrinsic declarations are typed by their mangled name; a
            // declaration whose name says p0 but whose type says p4 would
            // confuse every later intrinsic lookup.  They are unused anyway:
            // the rewritten calls ask Intrinsic::getDeclaration() for the
            // correctly typed overload.
            if (!F.isIntrinsic() && NFT != F.getFunctionType())
                decls.push_back(&F);
        } else {
            // Every definition is rebuilt, even when its signature does not
            // change: a kernel like `void(ptr addrspace(1))` keeps its type
            // while its *body* still holds address-space-0 pointers.
            defs.push_back(&F);
        }
    }
    if (getenv("OSL_VULKAN_LEGALIZE_TRACE")) {
        fprintf(stderr, "[legalize] decls=%zu defs=%zu\n", decls.size(),
                defs.size());
        for (auto* F : defs)
            fprintf(stderr, "[legalize]   def %s args=%u\n",
                    F->getName().str().c_str(), F->arg_size());
    }

    for (auto* F : decls) {
        Function* NF = Function::Create(
            cast<FunctionType>(mapType(F->getFunctionType())), F->getLinkage(),
            F->getAddressSpace(), F->getName() + ".vulkan", &M);
        NF->copyAttributesFrom(F);
        NF->setCallingConv(F->getCallingConv());
        m_values[F] = NF;
        // Call sites resolve their callee through m_functions, so a re-created
        // *declaration* has to be registered there as well: otherwise the
        // rebuilt call keeps pointing at the old declaration, which is erased
        // in the swap phase, and the module prints as `call <badref>`.
        m_functions[F] = NF;
    }

    for (auto* F : defs) {
        Function* NF = Function::Create(
            cast<FunctionType>(mapType(F->getFunctionType())), F->getLinkage(),
            F->getAddressSpace(), F->getName() + ".vulkan", &M);
        NF->copyAttributesFrom(F);
        NF->setCallingConv(F->getCallingConv());
        NF->setVisibility(F->getVisibility());
        for (unsigned i = 0; i < F->arg_size(); ++i) {
            NF->getArg(i)->setName(F->getArg(i)->getName());
            m_values[F->getArg(i)] = NF->getArg(i);
        }
        m_functions[F] = NF;
        m_values[F]    = NF;
    }

    // 3. Rebuild bodies.  All function shells exist by now, so calls resolve.
    for (auto* F : defs) {
        if (getenv("OSL_VULKAN_LEGALIZE_TRACE"))
            fprintf(stderr, "[legalize] rebuilding %s\n",
                    F->getName().str().c_str());
        if (!rebuildBody(F, m_functions[F], log))
            return false;
    }

    // 4. Swap in the new bodies, drop the old functions.  The old blocks are
    //    dead: the new function already holds rebuilt copies, so they are
    //    dropped rather than moved (moving them would duplicate the body and
    //    leave the old function referenced by its own instructions).
    for (auto* F : defs) {
        Function* NF = m_functions[F];
        if (getenv("OSL_VULKAN_LEGALIZE_TRACE"))
            fprintf(stderr, "[legalize] swap %s uses=%u\n",
                    F->getName().str().c_str(),
                    (unsigned)std::distance(F->use_begin(), F->use_end()));
        F->dropAllReferences();
        // Copy the name first: the StringRef points into the symbol table
        // entry that eraseFromParent() releases.
        std::string name = F->getName().str();
        F->eraseFromParent();
        NF->setName(name);
        if (getenv("OSL_VULKAN_LEGALIZE_TRACE"))
            fprintf(stderr, "[legalize]   renamed to %s\n", name.c_str());
    }
    for (auto* F : decls) {
        if (getenv("OSL_VULKAN_LEGALIZE_TRACE"))
            fprintf(stderr, "[legalize] decl swap %s\n",
                    F->getName().str().c_str());
        Function* NF = cast<Function>(m_values[F]);
        std::string name = F->getName().str();
        F->dropAllReferences();
        F->eraseFromParent();
        NF->setName(name);
    }
    if (getenv("OSL_VULKAN_LEGALIZE_TRACE"))
        fprintf(stderr, "[legalize] module rewritten\n");

    return true;
}

