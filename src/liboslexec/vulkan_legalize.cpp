/// Widen every i1 load/store in memory to i8.
///
/// A shader body with a branch keeps a bool in memory, e.g. the "layer not yet
/// initialised" flag OSL puts into the group-data block, or a `bool` local of
/// the shader itself.  clspv legalizes an i1 memory object by loading an i8 and
/// bitcasting it to i1 -- and `bitcast i8 %x to i1` is not a valid instruction,
/// so the whole module is rejected with
///   Invalid bitcast  %6431 = bitcast i8 %6430 to i1
///   LLVM ERROR: Broken module found, compilation aborted!
/// (which kills the renderer, not just the shader).  Widening the memory object
/// to i8 and doing the truncation with an icmp keeps the value identical and
/// leaves nothing for clspv to reject.
static void widen_i1_memory (llvm::Module& M)
{
    llvm::Type* i8   = llvm::Type::getInt8Ty(M.getContext());
    llvm::Value* one = llvm::ConstantInt::get(i8, 1);
    llvm::Value* zero = llvm::ConstantInt::get(i8, 0);
    (void)one;
    for (auto& F : M) {
        for (auto& bb : F) {
            for (auto it = bb.begin(); it != bb.end();) {
                llvm::Instruction* I = &*it++;
                if (auto* st = llvm::dyn_cast<llvm::StoreInst>(I)) {
                    llvm::Value* v = st->getValueOperand();
                    if (!v->getType()->isIntegerTy(1))
                        continue;
                    llvm::IRBuilder<> b(st);
                    llvm::Value* z = b.CreateZExt(v, i8);
                    b.CreateAlignedStore(z, st->getPointerOperand(),
                                        st->getAlign());
                    st->eraseFromParent();
                } else if (auto* ld = llvm::dyn_cast<llvm::LoadInst>(I)) {
                    if (!ld->getType()->isIntegerTy(1))
                        continue;
                    llvm::IRBuilder<> b(ld);
                    llvm::Value* x = b.CreateAlignedLoad(
                        i8, ld->getPointerOperand(), ld->getAlign());
                    llvm::Value* c = b.CreateICmpNE(x, zero);
                    ld->replaceAllUsesWith(c);
                    ld->eraseFromParent();
                }
            }
        }
    }
}

void vulkan_set_module_target (llvm::Module& M)
{
    // A module from the CPU JIT has no target information at all; clspv
    // overrides the triple but keeps whatever data layout is present, and
    // prefers a spirv64 one.
#if OSL_LLVM_VERSION < 210
    M.setTargetTriple("spirv64-unknown-vulkan");
#else
    // LLVM 21+ takes a Triple rather than a string.
    M.setTargetTriple(llvm::Triple("spirv64-unknown-vulkan"));
#endif
    M.setDataLayout(kSpirv64DataLayout);
}

bool vulkan_legalize_module (llvm::Module& M, std::string& out_log)
{
    g_rewritten_opcodes.clear();
    g_dropped.clear();
    g_notes.clear();

    Retyper R(M);
    std::string log;
    if (!R.run(log)) {
        out_log = log;
        return false;
    }
    widen_i1_memory(M);
    out_log = log;
    return true;
}

std::string vulkan_legalize_summary ()
{
    std::ostringstream os;
    os << "opcodes rewritten:";
    for (auto& s : g_rewritten_opcodes)
        os << ' ' << s;
    os << "\nnotes:";
    for (auto& s : g_notes)
        os << "\n  - " << s;
    os << '\n';
    return os.str();
}


// The device runtime, embedded as a byte array by CMake
// (MAKE_EMBEDDED_CPP over the bitcode clang produced from
// vulkan_shadeops.cpp).  See src/liboslexec/CMakeLists.txt.  These live in the
// global namespace (the serializer emits them outside any namespace), hence the
// explicit `::` at the use sites below.

bool vulkan_link_shadeops (llvm::Module& M, std::string& out_log)
{
    llvm::StringRef content(
        reinterpret_cast<const char*>(
            ::vulkan_shadeops_llvm_compiled_ops_block),
        (size_t)::vulkan_shadeops_llvm_compiled_ops_size);
    llvm::MemoryBufferRef buf(content, "vulkan_shadeops.bc");

    llvm::Expected<std::unique_ptr<llvm::Module>> mod_or_err
        = llvm::parseBitcodeFile(buf, M.getContext());
    if (!mod_or_err) {
        out_log = llvm::toString(mod_or_err.takeError());
        return false;
    }
    std::unique_ptr<llvm::Module> shadeops = std::move(*mod_or_err);

    // Diagnose what the two modules look like just before they are merged: if
    // the destination already carries generic-address-space pointers, the
    // verification failure that follows belongs to the group module, not to the
    // device runtime.
    if (getenv("OSL_VULKAN_LINK_TRACE")) {
        int g0 = 0, g4 = 0;
        for (auto& F : M)
            for (auto& BB : F)
                for (auto& I : BB)
                    for (auto& Op : I.operands())
                        if (auto* PT = llvm::dyn_cast<llvm::PointerType>(
                                Op->getType())) {
                            if (PT->getAddressSpace() == 4)
                                ++g4;
                            else if (PT->getAddressSpace() == 0)
                                ++g0;
                        }
        fprintf(stderr,
                "[vulkan-link] group module: as0=%d as4=%d dl='%s' triple='%s'\n",
                g0, g4, M.getDataLayoutStr().c_str(),
                M.getTargetTriple().str().c_str());
    }

    // The group module carries `declare` for each shadeop; linking the
    // definitions in replaces them (a definition always wins over a
    // declaration in the same module after llvm-link).
    if (llvm::Linker::linkModules(M, std::move(shadeops))) {
        out_log = "llvm linker rejected the device runtime";
        return false;
    }

    if (getenv("OSL_VULKAN_LINK_TRACE")) {
        std::string verr;
        llvm::raw_string_ostream vos(verr);
        bool bad = llvm::verifyModule(M, &vos);
        vos.flush();
        fprintf(stderr, "[vulkan-link] after link, broken=%d\n%s\n", (int)bad,
                verr.c_str());
        if (bad)
            return false;
    }

    // Anything still declared but never defined would make clspv emit a call
    // to a non-existent function, or refuse the module outright.  Name them so
    // the operator knows which shadeop is missing instead of reading a cryptic
    // clspv diagnostic.
    std::ostringstream missing;
    int nmissing = 0;
    for (auto& F : M) {
        if (F.isDeclaration() && !F.isIntrinsic() && F.getLinkage()
                != llvm::GlobalValue::AvailableExternallyLinkage) {
            // Skip the runtime-only entry points a module may still reference
            // (memset/memcpy come in as intrinsics, so they never land here).
            missing << ' ' << F.getName().str();
            ++nmissing;
        }
    }
    if (nmissing) {
        out_log = fmtformat("{} unresolved device function(s):{}", nmissing,
                            missing.str());
        return false;
    }
    return true;
}



